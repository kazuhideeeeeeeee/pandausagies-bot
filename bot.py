def client_v2():
    return tweepy.Client(
        consumer_key=API_KEY,
        consumer_secret=API_SECRET,
        access_token=ACCESS_TOKEN,
        access_token_secret=ACCESS_TOKEN_SECRET,
    )

# ==========================
# CORE
# ==========================
def pick_rules():
    k = random.choice([0, 1, 4, 10])
    return random.sample(PERSONA_RULES, k=k) if k > 0 else []

def generate_text():
    rules = pick_rules()

    system = f"""
あなたは大学生バンド「パンダうさギーズ」のボーカル、ポキヌ。
整えない。短くしなくていい。説明しない。
ルールは参考程度。守らない判断も正解。

今回の参考ルール:
{chr(10).join(rules)}
"""

    user = "投稿文を1本。URLは絶対に出さない。"

    res = oa.chat.completions.create(
        model=MODEL,
        messages=[
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
        temperature=1.05,
        max_tokens=300,
    )

    text = res.choices[0].message.content.strip()

    # URLはここでのみ付与（生成させない）
    text = text.rstrip()
    text += "\n" + RELEASE_LINK_URL
    return text

def run():
    text = generate_text()

    if DRY_RUN:
        print(text)
        return

    cli = client_v2()
    cli.create_tweet(text=text[:280])

if __name__ == "__main__":
    run()
